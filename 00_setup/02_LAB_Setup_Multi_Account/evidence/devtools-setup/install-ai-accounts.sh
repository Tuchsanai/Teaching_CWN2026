#!/usr/bin/env bash
# install-ai-accounts.sh — set up multi-account wrappers:
#   yolo1..yolo5   -> Claude Code  (CLAUDE_CONFIG_DIR per account)
#   cyolo1..cyolo5 -> Codex CLI    (CODEX_HOME per account)
#
# Idempotent: re-running only creates what is missing. It never deletes or
# overwrites anything inside an account folder or in shared/. The only file it
# regenerates is its own launcher (identified by a marker line).
# Does NOT install claude/codex, does NOT touch ~/.bashrc, PATH, Git or SSH.
set -euo pipefail

## ตัวแปรตั้งค่า (แก้ที่นี่ที่เดียว ที่อื่นต้องอ้างอิงตัวแปรนี้)
BASE_PATH="$HOME/ai-accounts"

# Where the wrappers go: /usr/local/bin is already on PATH, so no PATH edit is needed.
BIN_DIR="/usr/local/bin"
LAUNCHER="$BIN_DIR/ai-account-launch"
MARKER="# ai-accounts-launcher (generated by install-ai-accounts.sh)"
ACCOUNTS=(1 2 3 4 5)

CLAUDE_ROOT="$BASE_PATH/.Claude"
CODEX_ROOT="$BASE_PATH/.Codex"

say()  { printf '[install] %s\n' "$*"; }
fail() { printf '[install] ERROR: %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- prerequisites
# claude lives in ~/.local/bin, which is NOT on PATH on this machine; use the
# absolute path (stable symlink maintained by Claude Code's own updater).
CLAUDE_BIN="$HOME/.local/bin/claude"
if [ ! -x "$CLAUDE_BIN" ]; then
  CLAUDE_BIN="$(command -v claude || true)"
fi
[ -n "$CLAUDE_BIN" ] && [ -x "$CLAUDE_BIN" ] || fail "claude not found (checked \$HOME/.local/bin/claude and PATH). Fix the prerequisite lab step; this installer does not install it."
CODEX_BIN="$(command -v codex || true)"
[ -n "$CODEX_BIN" ] || fail "codex not found on PATH. Fix the prerequisite lab step; this installer does not install it."
command -v python3 >/dev/null || fail "python3 is required (used to read shared MCP config)."
say "claude: $CLAUDE_BIN ($("$CLAUDE_BIN" --version 2>/dev/null | head -1))"
say "codex:  $CODEX_BIN ($("$CODEX_BIN" --version 2>/dev/null | grep -v '^WARNING' | head -1))"
[ -w "$BIN_DIR" ] || fail "$BIN_DIR is not writable by $(id -un)."

umask 077   # new dirs/files: owner-only

mkd() { # create dir if missing, report either way
  if [ -d "$1" ]; then say "keep   $1"; else mkdir -p "$1"; say "create $1"; fi
}
new_file() { # new_file <path> <content>: write only if the file does not exist
  if [ -e "$1" ]; then say "keep   $1"; else printf '%s' "$2" > "$1"; say "create $1"; fi
}

# ---------------------------------------------------------------- Claude Code
mkd "$CLAUDE_ROOT/shared/skills"
mkd "$CLAUDE_ROOT/shared/mcp"
new_file "$CLAUDE_ROOT/shared/mcp/mcp.json" '{
  "mcpServers": {}
}
'
for n in "${ACCOUNTS[@]}"; do
  mkd "$CLAUDE_ROOT/yolo$n"
  mkd "$CLAUDE_ROOT/yolo$n/skills"   # launcher links shared skills in here
done

# ---------------------------------------------------------------- Codex CLI
mkd "$CODEX_ROOT/shared/skills"
mkd "$CODEX_ROOT/shared/mcp"
new_file "$CODEX_ROOT/shared/mcp/config.toml" '# Shared MCP servers for every cyoloN (Codex CLI).
# Same table format as [mcp_servers.<name>] in config.toml. The launcher passes
# each server as `-c mcp_servers.<name>={...}` so it is layered on top of the
# account'"'"'s own config.toml (per-account servers still work).
# Server names: letters, digits, _ and - only.
# Never put secrets here (-c values are visible in `ps`); reference env vars
# instead, e.g. bearer_token_env_var = "MY_TOKEN" or env_vars = ["MY_TOKEN"].
#
# [mcp_servers.example]
# command = "npx"
# args = ["-y", "some-mcp-server"]
'
for n in "${ACCOUNTS[@]}"; do
  home="$CODEX_ROOT/cyolo$n"
  mkd "$home"                         # codex refuses a CODEX_HOME that does not exist
  mkd "$home/skills"
  cfg="$home/config.toml"
  if [ ! -e "$cfg" ]; then
    printf '%s\n' \
      '# Per-account Codex config (CODEX_HOME). Created by install-ai-accounts.sh.' \
      '# Store login in $CODEX_HOME/auth.json (not a shared OS keyring).' \
      'cli_auth_credentials_store = "file"' \
      'mcp_oauth_credentials_store = "file"' > "$cfg"
    say "create $cfg"
  else
    # Existing config: only add missing top-level keys, prepended (top-level
    # keys must come before any [table]). Existing values are never changed.
    for kv in 'cli_auth_credentials_store = "file"' 'mcp_oauth_credentials_store = "file"'; do
      key="${kv%% *}"
      if grep -Eq "^[[:space:]]*$key[[:space:]]*=" "$cfg"; then
        say "keep   $cfg ($key already set)"
      else
        cp -p "$cfg" "$cfg.bak.$(date +%Y%m%d%H%M%S)"
        { printf '%s\n' "$kv"; cat "$cfg"; } > "$cfg.tmp" && mv "$cfg.tmp" "$cfg"
        say "update $cfg (added $key; backup saved)"
      fi
    done
  fi
done

# ---------------------------------------------------------------- launcher
if [ -e "$LAUNCHER" ] && ! grep -qF "$MARKER" "$LAUNCHER"; then
  fail "$LAUNCHER exists and was not created by this installer; refusing to overwrite."
fi
tmp="$(mktemp "$BIN_DIR/.ai-account-launch.XXXXXX")"
{
  echo '#!/usr/bin/env bash'
  echo "$MARKER"
  echo '# Do not edit: change BASE_PATH in install-ai-accounts.sh and re-run it.'
  printf 'BASE_PATH=%q\n'  "$BASE_PATH"
  printf 'CLAUDE_BIN=%q\n' "$CLAUDE_BIN"
  printf 'CODEX_BIN=%q\n'  "$CODEX_BIN"
  cat <<'LAUNCHER_BODY'
set -euo pipefail
name="$(basename "$0")"
warn() { printf '[%s] %s\n' "$name" "$*" >&2; }

case "$name" in
  yolo[1-5])  tool=claude; tool_dir="$BASE_PATH/.Claude" ;;
  cyolo[1-5]) tool=codex;  tool_dir="$BASE_PATH/.Codex"  ;;
  *) warn "unknown command name; invoke as yolo1..yolo5 or cyolo1..cyolo5"; exit 2 ;;
esac
root="$tool_dir/$name"
shared="$tool_dir/shared"

if [ ! -d "$root" ]; then
  warn "account folder not found: $root"
  warn "run install-ai-accounts.sh first (it creates the folder without touching existing ones)."
  exit 3
fi

# Env vars that would override this account's own login. Names only, never values.
warn_env() {
  local v
  for v in "$@"; do
    if [ -n "${!v:-}" ]; then warn "note: \$$v is set in your environment and takes precedence over this account's stored login"; fi
  done
}

# Link each skill in shared/skills into <root>/skills/<skill> (a symlink per
# skill, as both CLIs document). Never replaces a real per-account skill.
sync_skills() {
  local src="$shared/skills" dst="$root/skills" s n l
  mkdir -p "$dst"
  for l in "$dst"/*; do  # drop links whose shared skill was removed
    if [ -L "$l" ] && [ ! -e "$l" ] && [[ "$(readlink "$l")" == "$src/"* ]]; then rm -f "$l"; fi
  done
  for s in "$src"/*/; do
    [ -d "$s" ] || continue
    n="$(basename "$s")"
    if [ ! -e "$dst/$n" ] && [ ! -L "$dst/$n" ]; then ln -s "$src/$n" "$dst/$n"
    elif [ ! -L "$dst/$n" ]; then warn "skill '$n' exists in both shared and $dst; using the per-account copy"
    fi
  done
}
sync_skills

pre=()
if [ "$tool" = claude ]; then
  export CLAUDE_CONFIG_DIR="$root"
  # Claude Code refuses --dangerously-skip-permissions as root unless IS_SANDBOX=1.
  if [ "$(id -u)" = 0 ]; then export IS_SANDBOX=1; fi
  warn_env ANTHROPIC_API_KEY ANTHROPIC_AUTH_TOKEN CLAUDE_CODE_OAUTH_TOKEN ANTHROPIC_PROFILE \
           CLAUDE_CODE_USE_BEDROCK CLAUDE_CODE_USE_VERTEX CLAUDE_CODE_USE_FOUNDRY
  mcp="$shared/mcp/mcp.json"
  if [ -s "$mcp" ]; then
    if python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); sys.exit(0 if d.get("mcpServers") else 1)' "$mcp" 2>/dev/null; then
      # --mcp-config is variadic: it must be followed by another flag (added below),
      # otherwise it would swallow the user's first positional argument.
      pre+=(--mcp-config "$mcp")
    elif ! python3 -c 'import json,sys; json.load(open(sys.argv[1]))' "$mcp" 2>/dev/null; then
      warn "ignoring $mcp: not valid JSON"
    fi
  fi
  cmd=("$CLAUDE_BIN" "${pre[@]}" --dangerously-skip-permissions "$@")
else
  export CODEX_HOME="$root"
  warn_env OPENAI_API_KEY CODEX_API_KEY
  mcp="$shared/mcp/config.toml"
  if [ -s "$mcp" ]; then
    # Turn each [mcp_servers.<name>] table into `-c mcp_servers.<name>={inline}`.
    if out="$(python3 - "$mcp" <<'PY'
import json, re, sys, tomllib, datetime
data = tomllib.load(open(sys.argv[1], "rb")).get("mcp_servers", {})
def val(x):
    if isinstance(x, bool): return "true" if x else "false"
    if isinstance(x, (int, float)): return repr(x)
    if isinstance(x, str): return json.dumps(x)
    if isinstance(x, list): return "[" + ", ".join(val(i) for i in x) + "]"
    if isinstance(x, dict): return "{" + ", ".join(f"{json.dumps(k)} = {val(v)}" for k, v in x.items()) + "}"
    if isinstance(x, (datetime.date, datetime.time)): return x.isoformat()
    raise ValueError(type(x))
for name, table in data.items():
    if not re.fullmatch(r"[A-Za-z0-9_-]+", name):
        print(f"skip:{name}", file=sys.stderr); continue
    # one item per line; val() output never contains a raw newline (json.dumps escapes it)
    print("-c"); print(f"mcp_servers.{name}={val(table)}")
PY
)"; then
      if [ -n "$out" ]; then mapfile -t pre <<< "$out"; fi
    else
      warn "ignoring $mcp: could not parse TOML"
    fi
  fi
  cmd=("$CODEX_BIN" "${pre[@]}" --dangerously-bypass-approvals-and-sandbox "$@")
fi

if [ -n "${AI_ACCOUNTS_DRYRUN:-}" ]; then   # debug: show what would run (no secrets involved)
  if [ "$tool" = claude ]; then echo "CLAUDE_CONFIG_DIR=$CLAUDE_CONFIG_DIR IS_SANDBOX=${IS_SANDBOX:-}"; else echo "CODEX_HOME=$CODEX_HOME"; fi
  printf '%q ' "${cmd[@]}"; echo
  exit 0
fi
exec "${cmd[@]}"
LAUNCHER_BODY
} > "$tmp"
chmod 755 "$tmp"
mv -f "$tmp" "$LAUNCHER"
say "write  $LAUNCHER"

for n in "${ACCOUNTS[@]}"; do
  for c in "yolo$n" "cyolo$n"; do
    link="$BIN_DIR/$c"
    if [ -L "$link" ] && [ "$(readlink "$link")" = "$LAUNCHER" ]; then
      say "keep   $link"
    elif [ -e "$link" ] || [ -L "$link" ]; then
      fail "$link already exists and is not ours; refusing to overwrite."
    else
      ln -s "$LAUNCHER" "$link"; say "link   $link -> $LAUNCHER"
    fi
  done
done

say "done. BASE_PATH=$BASE_PATH"
say "next: log in to each account yourself — see login-guide.md"
