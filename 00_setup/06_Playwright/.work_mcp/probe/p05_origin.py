import re, time
from probe_util import Probe, find_ref, snap_yaml
p = Probe("p05_origin", config="mcp.config.boxes.json")
N = open("p05_origin_findings.txt", "w")
def note(*a):
    s = " ".join(str(x) for x in a); print(s); N.write(s + "\n"); N.flush()
def autofile(text):
    m = re.search(r"### Snapshot\n- \[Snapshot\]\(([^)]+)\)", text)
    return (m.group(1), open(m.group(1)).read()) if m else (None, None)
r = p.call("browser_navigate", {"url": "https://www.google.com/travel/flights?hl=en"}, "open")
f, body = autofile(r["_text"])
note("auto file has box (config snapshot.boxes)?", "[box=" in body)
y = snap_yaml(p.call("browser_snapshot", {}, "snapshot (config boxes)", maxtext=1500)["_text"])
WF, l = find_ref(y, r'combobox "Where from\?')
note("WF", WF, l)
r = p.call("browser_click", {"target": WF, "element": "Where from?"}, "click Where from")
f, body = autofile(r["_text"])
EXP, l = find_ref(body, r'\[expanded\]')
note("from auto-file (no explicit snapshot): expanded", EXP, l, "WF still in auto-file?", f"[ref={WF}]" in body)
# ใช้ ref เก่า WF พิมพ์
r = p.call("browser_type", {"target": WF, "text": "BKK", "element": "Where from? (old ref)"}, "type ด้วย ref เก่า WF")
note("type old ref isError", r["result"].get("isError"), r["_text"][:200].replace("\n", " | "))
r = p.call("browser_type", {"target": EXP, "text": "BKK", "element": "Where else?"}, "type BKK ด้วย ref จาก auto-file")
note("type resp has snapshot section?", "### Snapshot" in r["_text"], "bytes", r["_bytes"])
time.sleep(1)
r = p.call("browser_snapshot", {}, "snapshot หลังพิมพ์", maxtext=2500)
y = snap_yaml(r["_text"])
note("EXP still there?", f"[ref={EXP}]" in y, find_ref(y, r'\[expanded\]'))
SUV, l = find_ref(y, r'option "Suvarnabhumi Airport \(BKK\)"')
note("SUV", SUV, l)
r = p.call("browser_click", {"target": SUV, "element": "Suvarnabhumi"}, "click Suvarnabhumi")
f, body = autofile(r["_text"])
note("verify in auto-file:", find_ref(body, r'combobox "Where from\?.*BKK'), "expanded left:", "[expanded]" in body)
r = p.call("browser_press_key", {"key": "Escape"}, "press Escape (has snapshot?)")
note("press_key has snapshot?", "### Snapshot" in r["_text"])
r = p.call("browser_hover", {"target": find_ref(body, r'combobox "Where to\?')[0], "element": "Where to"}, "hover (has snapshot?)")
note("hover has snapshot?", "### Snapshot" in r["_text"])
p.call("browser_close", {}, "close")
p.close()
