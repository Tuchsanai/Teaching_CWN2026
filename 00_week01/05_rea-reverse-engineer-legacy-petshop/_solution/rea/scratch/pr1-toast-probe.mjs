// PR-1 probe: outerHTML of the toast (success vs. stock-warning) + qty-input value when pressing + past stock. Resets data first.
import { chromium } from 'playwright';
const B = process.env.BASE_URL ?? 'http://localhost:4000';
await fetch(`${B}/api/test/reset`, { method: 'POST' });
const browser = await chromium.launch();
const page = await (await browser.newContext({ baseURL: B, locale: 'th-TH' })).newPage();
const ready = () => page.locator('html[data-ready="true"]').waitFor({ state: 'attached' });
await page.goto('/products/hairball-control-dry'); await ready();
for (let i = 0; i < 5; i++) await page.getByTestId('qty-plus').click({ trial: false }).catch((e) => console.log('plus err', e.message.split('\n')[0]));
console.log('qty-input after 5x plus =', await page.getByTestId('qty-input').inputValue(), 'max=', await page.getByTestId('qty-input').getAttribute('max'));
await page.goto('/products/hairball-control-dry'); await ready();
await page.getByTestId('add-to-cart').click();
console.log('success toast:', await page.getByTestId('toast').evaluate((e) => e.outerHTML.slice(0, 400)));
await page.goto('/products/hairball-control-dry'); await ready();
await page.getByTestId('qty-plus').click(); await page.getByTestId('qty-plus').click();
await page.getByTestId('add-to-cart').click(); await page.waitForTimeout(300);
console.log('round2 toast (asked 3, 2 left):', await page.getByTestId('toast').evaluate((e) => e.outerHTML.slice(0, 400)));
await page.goto('/products/hairball-control-dry'); await ready();
await page.getByTestId('add-to-cart').click(); await page.waitForTimeout(300);
console.log('round3 toast (full):', await page.getByTestId('toast').evaluate((e) => e.outerHTML.slice(0, 400)));
await browser.close();
