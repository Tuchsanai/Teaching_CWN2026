export type DictKey = keyof typeof D;
export type ErrorCode = DictKey extends `err_${infer C}` ? C : never;

const IDX: Record<Lang, 0 | 1 | 2> = { th: 0, en: 1, zh: 2 };

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const entry = D[key] as Entry | undefined;
  let s = entry ? entry[IDX[lang]] : String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function errorText(lang: Lang, code: string): string {
  const key = `err_${code}` as DictKey;
  return key in D ? translate(lang, key) : translate(lang, "err_SERVER");
}

/** pick the right column of a {th,en,zh} record from the database */
export function pick<T extends Record<string, unknown>>(row: T, field: string, lang: Lang): string {
  const v = row[`${field}_${lang}`] ?? row[`${field}_en`] ?? row[`${field}_th`];
  return typeof v === "string" ? v : "";
}
