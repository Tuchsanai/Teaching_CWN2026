from pathlib import Path
from datetime import datetime, timezone
import json
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parent
results=[]
def passed(name):
    results.append({'case':name,'result':'PASS'})
def no_overflow(page):
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1100},reduced_motion='reduce')
    page=context.new_page()
    errors=[]; network=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:network.append(r.url) if r.url.startswith(('http:','https:')) else None)
    page.route('**/*',lambda route:route.abort() if route.request.url.startswith(('http:','https:')) else route.continue_())
    page.clock.install(time=datetime(2030,1,15,7,0,tzinfo=timezone.utc))
    try:
        page.goto((ROOT/'output.html').as_uri())
        expect(page.locator('.room-card')).to_have_count(4)
        expect(page.get_by_role('heading',name='พื้นที่สำหรับไอเดียดี ๆ')).to_be_visible()
        no_overflow(page)
        passed('เปิดจาก file:// ได้ มีห้อง 4 ห้อง และ desktop ไม่ล้นแนวนอน')
        page.screenshot(path=str(ROOT/'preview-desktop.png'),full_page=True,animations='disabled')
        page.get_by_label('จำนวนผู้เข้าร่วม',exact=True).select_option('12')
        expect(page.locator('.room-card')).to_have_count(2)
        passed('กรองห้องตามความจุ')
        page.get_by_label('ค้นหาห้องหรืออุปกรณ์').fill('โปรเจกเตอร์')
        expect(page.locator('.room-card')).to_have_count(2)
        page.get_by_label('ค้นหาห้องหรืออุปกรณ์').fill('ไม่มีห้องนี้')
        expect(page.get_by_role('heading',name='ไม่พบห้องที่ตรงกับการค้นหา')).to_be_visible()
        page.get_by_role('button',name='ล้างตัวกรอง').click()
        expect(page.locator('.room-card')).to_have_count(4)
        passed('ค้นหาอุปกรณ์ สถานะไม่พบข้อมูล และล้างตัวกรอง')
        page.get_by_label('วันที่ใช้ห้อง').fill('2030-01-16')
        page.get_by_role('button',name='ตารางเวลา').click()
        slot=page.get_by_role('button',name='ห้องต้นไทร 09:00–09:30 ว่าง',exact=True)
        expect(slot).to_be_enabled();slot.click()
        expect(page.get_by_label('วันที่',exact=True)).to_have_value('2030-01-16')
        expect(page.get_by_label('เวลาเริ่ม',exact=True)).to_have_value('09:00')
        passed('ตารางเวลาเลือกวันที่และคลิกช่วงว่างเพื่อเปิดแบบฟอร์ม')
        page.get_by_label('หัวข้อการประชุม').fill('ทดสอบประชุมทีม')
        page.get_by_label('ผู้เข้าร่วม (คน)').fill('9')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        assert page.get_by_label('ผู้เข้าร่วม (คน)').evaluate('(e)=>e.validity.rangeOverflow')
        expect(page.get_by_role('dialog',name='จองห้องประชุม',exact=True)).to_be_visible()
        passed('ปฏิเสธจำนวนคนเกินความจุห้อง')
        page.get_by_label('ผู้เข้าร่วม (คน)').fill('5')
        page.get_by_label('เวลาสิ้นสุด').select_option('08:30')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        expect(page.get_by_role('alert')).to_have_text('เวลาสิ้นสุดต้องอยู่หลังเวลาเริ่ม')
        passed('ปฏิเสธเวลาสิ้นสุดก่อนเวลาเริ่ม')
        page.get_by_label('เวลาสิ้นสุด').select_option('10:00')
        page.get_by_label('หัวข้อการประชุม').fill('   ')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        expect(page.get_by_role('alert')).to_have_text('กรุณาระบุหัวข้อการประชุม')
        passed('ปฏิเสธหัวข้อที่มีแต่ช่องว่าง')
        page.get_by_label('หัวข้อการประชุม').fill('ทดสอบประชุมทีม')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        booking=page.locator('.booking').filter(has=page.get_by_role('heading',name='ทดสอบประชุมทีม',exact=True))
        expect(booking.get_by_text('ยืนยันแล้ว',exact=True)).to_be_visible()
        expect(booking).to_contain_text('09:00–10:00')
        passed('จองสำเร็จและแสดงสถานะยืนยันแล้ว')
        page.reload()
        page.get_by_role('button',name='การจองของฉัน',exact=True).click()
        expect(booking).to_be_visible()
        passed('ข้อมูลการจองคงอยู่หลังโหลดไฟล์ใหม่')
        page.get_by_role('button',name='ค้นหาห้องประชุม',exact=True).click()
        page.get_by_label('วันที่ใช้ห้อง').fill('2030-01-16')
        page.get_by_role('button',name='ตารางเวลา').click()
        expect(page.get_by_role('button',name='ห้องต้นไทร 09:00–09:30 มีการจอง',exact=True)).to_be_disabled()
        passed('การจองปรากฏเป็นช่วงไม่ว่างในตาราง')
        page.get_by_role('button',name='＋ จองห้องประชุม',exact=True).click()
        page.get_by_label('หัวข้อการประชุม').fill('จองทับซ้อน')
        page.get_by_label('เวลาเริ่ม',exact=True).select_option('09:30')
        page.get_by_label('เวลาสิ้นสุด').select_option('10:30')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        expect(page.get_by_role('alert')).to_contain_text('ช่วงเวลานี้มีการจองแล้ว')
        passed('ปฏิเสธการจองทับซ้อนบางส่วน')
        page.get_by_label('เวลาเริ่ม',exact=True).select_option('10:00')
        page.get_by_label('เวลาสิ้นสุด').select_option('10:30')
        page.get_by_label('หัวข้อการประชุม').fill('<img src=x onerror=alert(1)>')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        expect(page.get_by_role('heading',name='<img src=x onerror=alert(1)>',exact=True)).to_be_visible()
        expect(page.locator('.booking img')).to_have_count(0)
        passed('จองติดกันได้และแสดงหัวข้อเป็นข้อความโดยไม่รัน HTML')
        booking.get_by_role('button',name='ยกเลิกการจอง',exact=True).click()
        page.get_by_role('button',name='เก็บการจองไว้').click()
        expect(booking.get_by_text('ยืนยันแล้ว',exact=True)).to_be_visible()
        passed('กลับจากหน้ายกเลิกแล้วการจองยังอยู่')
        booking.get_by_role('button',name='ยกเลิกการจอง',exact=True).click()
        page.get_by_role('button',name='ยืนยันยกเลิก',exact=True).click()
        expect(booking.get_by_text('ยกเลิกแล้ว',exact=True)).to_be_visible()
        page.get_by_label('กรองสถานะ').select_option('cancelled')
        expect(page.locator('.booking')).to_have_count(1)
        passed('ยกเลิกการจองและกรองสถานะยกเลิกแล้ว')
        page.get_by_role('button',name='ค้นหาห้องประชุม',exact=True).click()
        expect(page.get_by_role('button',name='ห้องต้นไทร 09:00–09:30 ว่าง',exact=True)).to_be_enabled()
        passed('ยกเลิกแล้วคืนเวลาว่าง')
        page.reload()
        page.get_by_role('button',name='การจองของฉัน',exact=True).click()
        expect(booking.get_by_text('ยกเลิกแล้ว',exact=True)).to_be_visible()
        passed('สถานะยกเลิกคงอยู่หลังโหลดใหม่')
        page.get_by_role('button',name='＋ จองห้องประชุม',exact=True).click()
        page.get_by_label('หัวข้อการประชุม').fill('ย้อนหลัง')
        page.get_by_label('วันที่',exact=True).fill('2030-01-14')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        assert page.get_by_label('วันที่',exact=True).evaluate('(e)=>e.validity.rangeUnderflow')
        page.keyboard.press('Escape')
        expect(page.get_by_role('dialog')).to_have_count(0)
        passed('ปฏิเสธวันย้อนหลังและปิด dialog ด้วย Escape')
        page.clock.set_fixed_time(datetime(2030,1,17,7,0,tzinfo=timezone.utc))
        page.get_by_label('กรองสถานะ').select_option('completed')
        expect(page.locator('.booking')).to_have_count(3)
        expect(page.locator('.booking .danger')).to_have_count(0)
        passed('รายการที่หมดเวลาแสดงเสร็จสิ้นและไม่มีปุ่มยกเลิก')
        page.set_viewport_size({'width':390,'height':844})
        page.get_by_role('button',name='ค้นหาห้องประชุม',exact=True).click()
        page.get_by_label('วันที่ใช้ห้อง').fill('2030-01-18')
        no_overflow(page)
        page.screenshot(path=str(ROOT/'preview-mobile.png'),full_page=True,animations='disabled')
        page.get_by_role('button',name='ตารางเวลา').click()
        no_overflow(page)
        page.get_by_role('button',name='ห้องต้นไทร 09:00–09:30 ว่าง',exact=True).click()
        page.get_by_label('หัวข้อการประชุม').fill('Mobile booking')
        page.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        mobile=page.locator('.booking').filter(has=page.get_by_role('heading',name='Mobile booking',exact=True))
        expect(mobile.get_by_text('ยืนยันแล้ว',exact=True)).to_be_visible()
        no_overflow(page)
        passed('มือถือ 390×844 แสดงผลไม่ล้นและจองได้จริง')
        assert not errors,errors
        assert not network,network
        passed('ไม่มี JavaScript error และไม่มีคำขอ HTTP/HTTPS ตลอดเส้นทางหลัก')
        isolated=browser.new_context(viewport={'width':390,'height':844})
        fallback=isolated.new_page()
        fallback.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked')}})")
        fallback.goto((ROOT/'output.html').as_uri())
        expect(fallback.locator('#storageWarning')).to_be_visible()
        fallback.get_by_role('button',name='＋ จองห้องประชุม',exact=True).click()
        fallback.get_by_label('วันที่',exact=True).fill('2099-01-15')
        fallback.get_by_label('หัวข้อการประชุม').fill('Memory fallback')
        fallback.get_by_role('button',name='ยืนยันการจอง',exact=True).click()
        expect(fallback.get_by_role('heading',name='Memory fallback',exact=True)).to_be_visible()
        passed('เมื่อ localStorage ถูกบล็อกยังจองได้และแจ้งข้อจำกัดการเก็บข้อมูล')
        isolated.close()
    except Exception as exc:
        results.append({'case':'Execution failure','result':'FAIL','detail':str(exc)})
        page.screenshot(path=str(ROOT/'test-failure.png'),full_page=True)
        raise
    finally:
        (ROOT/'test-results.json').write_text(json.dumps({'browser':'Chromium headless','url':'file:// output.html','viewports':['1440×1100','390×844'],'fixed_test_date':'2030-01-15 07:00 UTC; advanced to 2030-01-17 for expiry check','results':results,'javascript_errors':errors,'network_requests':network},ensure_ascii=False,indent=2))
        print(json.dumps(results,ensure_ascii=False,indent=2))
        browser.close()
