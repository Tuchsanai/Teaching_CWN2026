def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (หลีกเลี่ยงปัญหา float) ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3 or amount <= 0:
        return 0
    # หน่วยเป็น 1/10000 ของ amount: 0.75% = 75, 15% = 1500
    rate = min(75 * days_late, 1500)
    return (amount * rate + 5000) // 10000
