def shipping_fee(weight_g, distance_km, express):
    need_int(weight_g, "weight_g", 1, 30000)
    need_int(distance_km, "distance_km", 0)
    need_bool(express, "express")
    # นโยบาย S2: ส่งด่วนรับน้ำหนักไม่เกิน 20000 กรัม
    if express and weight_g > 20000:
        raise ValueError("ส่งด่วนไม่เกิน 20000 กรัม")
    # นโยบาย S1: ระยะ 0 = รับเองที่ร้าน ค่าส่ง 0
    if distance_km == 0:
        return 0
    if weight_g <= 1000:
        baht = Fraction(40)
    elif weight_g <= 5000:
        baht = Fraction(80)
    else:
        baht = 80 + Fraction(weight_g - 5000, 1000) * 15
    if distance_km > 100:
        baht *= Fraction(120, 100)
    if express:
        baht *= Fraction(150, 100)
    return half_up(baht * 100)  # สตางค์ ปัดครึ่งขึ้นครั้งเดียว


TARGET = "shipping_fee"


def main():
    try:
        args = json.load(sys.stdin)
        if not isinstance(args, dict):
            raise ValueError("input ต้องเป็น JSON object")
        result = globals()[TARGET](**args)
    except (ValueError, TypeError) as error:
        print(json.dumps({"ok": False, "error": str(error)}))
        return 2
    print(json.dumps({"ok": True, "result": result}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
