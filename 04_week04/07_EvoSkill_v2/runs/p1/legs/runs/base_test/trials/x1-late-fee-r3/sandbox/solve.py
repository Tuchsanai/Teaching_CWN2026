def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, คืนจำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    ใช้เลขจำนวนเต็มล้วน (ไม่มีปัญหา float) ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # อัตรา หน่วย 0.01% : 0.75% = 75, 15% = 1500
    rate = min(75 * days_late, 1500)
    return (amount * rate * 2 + 10000) // 20000
