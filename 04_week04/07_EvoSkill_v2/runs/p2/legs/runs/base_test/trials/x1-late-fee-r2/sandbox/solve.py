def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, คืนค่าเป็น int)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (ไม่มีความคลาดเคลื่อนของ float) ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วยเป็น 1/10000 ของสตางค์: 0.75% = 75, 15% = 1500
    num = amount * min(75 * days_late, 1500)
    return (num + 5000) // 10000
