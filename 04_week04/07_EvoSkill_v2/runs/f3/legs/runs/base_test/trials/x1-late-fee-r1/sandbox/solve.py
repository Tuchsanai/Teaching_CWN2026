def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ของยอดต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยเลขจำนวนเต็มเพื่อเลี่ยงปัญหา float; ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3 or amount <= 0:
        return 0
    # rate เป็นหน่วย 1/10000: 0.75% = 75, 15% = 1500
    rate = min(75 * days_late, 1500)
    return (amount * rate * 2 + 10000) // 20000
