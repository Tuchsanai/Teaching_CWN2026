def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอดต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอด
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float และปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วย: basis points (1/10000) -> 0.75% = 75 bp, 15% = 1500 bp
    rate_bp = min(75 * days_late, 1500)
    return (amount * rate_bp + 5000) // 10000
