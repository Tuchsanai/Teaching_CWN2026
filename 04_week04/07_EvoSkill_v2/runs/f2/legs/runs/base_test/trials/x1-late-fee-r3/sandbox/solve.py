def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอด
    คำนวณด้วยเลขจำนวนเต็มล้วน ปัดเศษลง
    """
    if days_late <= 3:
        return 0
    fee = amount * 75 * days_late // 10000
    cap = amount * 15 // 100
    return min(fee, cap)
