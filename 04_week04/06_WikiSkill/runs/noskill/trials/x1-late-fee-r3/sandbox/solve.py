def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวัน (รวม 3 วันแรก)
    - สูงสุด 15% ของยอด
    คำนวณด้วยจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float และปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วย: 1/10000 ของสตางค์  (0.75% = 75/10000, 15% = 1500/10000)
    fee = min(amount * 75 * days_late, amount * 1500)
    return (fee + 5000) // 10000
