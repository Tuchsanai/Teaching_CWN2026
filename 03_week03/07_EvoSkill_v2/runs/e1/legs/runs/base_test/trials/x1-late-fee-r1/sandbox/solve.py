def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน ของยอดค้าง นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้าง
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # 0.75% * days = 75 * days / 10000 ; เพดาน 15% = 1500 / 10000
    basis_points_x100 = min(75 * days_late, 1500)
    return (amount * basis_points_x100 * 2 + 10000) // 20000
