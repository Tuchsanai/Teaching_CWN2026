def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ของยอดต่อวัน นับทุกวันที่ช้า
    - สูงสุด 15% ของยอด
    คำนวณด้วยจำนวนเต็มล้วนเพื่อเลี่ยงความคลาดเคลื่อนของ float
    ปัดเศษครึ่งขึ้น (round half up)
    """
    if days_late <= 3:
        return 0
    # หน่วยเป็น 1/10000 ของสตางค์: 0.75% = 75, 15% = 1500
    numerator = min(amount * 75 * days_late, amount * 1500)
    return (numerator + 5000) // 10000
