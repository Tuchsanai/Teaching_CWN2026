def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอด
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงความคลาดเคลื่อนของ float
    ปัดเศษแบบครึ่งขึ้น (half up) หลังจำกัดเพดานแล้ว
    """
    if days_late <= 3:
        return 0
    # เศษส่วนของยอด หน่วย 1/10000: วันละ 75, เพดาน 1500
    bp = min(75 * days_late, 1500)
    return (amount * bp * 2 + 10000) // 20000
