def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, คืนค่าเป็นจำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดเศษลง (floor)
    """
    if days_late <= 3:
        return 0
    # 0.75% = 75/10000, 15% = 1500/10000
    rate_bp = min(75 * days_late, 1500)  # หน่วย 1/10000
    return amount * rate_bp // 10000
