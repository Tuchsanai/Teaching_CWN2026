"""แม่แบบ solve.py สำหรับฟังก์ชันคิดเงิน BaanKafe (แก้เฉพาะส่วน FUNCTION)"""
import json
import sys
from fractions import Fraction


def half_up(x):
    """ปัดครึ่งขึ้นเป็นจำนวนเต็มสตางค์ (x ไม่ติดลบ) ใช้กับยอดที่ลูกค้าจ่าย"""
    return int((Fraction(x) * 2 + 1) // 2)


def round_down(x):
    """ปัดลง ใช้กับเงินที่ร้านจ่ายออก (เงินคืน/แต้ม)"""
    return int(Fraction(x) // 1)


def need_int(value, name, low=None, high=None):
    if type(value) is not int:  # bool และ float ไม่ใช่ int
        raise ValueError(f"{name} ต้องเป็นจำนวนเต็ม")
    if (low is not None and value < low) or (high is not None and value > high):
        raise ValueError(f"{name} อยู่นอกช่วงที่กำหนด")
    return value


def need_bool(value, name):
    if type(value) is not bool:
        raise ValueError(f"{name} ต้องเป็น True หรือ False")
    return value


def need_choice(value, name, allowed):
    if type(value) is not str or value not in allowed:
        raise ValueError(f"{name} ต้องเป็นหนึ่งใน {sorted(allowed)}")
    return value


# ---------------- FUNCTION ----------------
def shipping_fee(weight_g, distance_km, express):
    need_int(weight_g, "weight_g", 1, 30000)
    if type(distance_km) not in (int, float):
        raise ValueError("distance_km ต้องเป็นตัวเลข")
    if distance_km != distance_km or distance_km in (float("inf"), float("-inf")):
        raise ValueError("distance_km ต้องเป็นจำนวนจำกัด")
    if distance_km < 0:
        raise ValueError("distance_km ต้องไม่ติดลบ")
    need_bool(express, "express")
    if express and weight_g > 20000:
        raise ValueError("ส่งด่วนรับไม่เกิน 20,000 กรัม")
    if distance_km == 0:  # รับเองที่ร้าน
        return 0
    if weight_g <= 1000:
        baht = Fraction(40)
    elif weight_g <= 5000:
        baht = Fraction(80)
    else:
        baht = 80 + Fraction(15 * (weight_g - 5000), 1000)
    value = baht * 100  # สตางค์
    if Fraction(distance_km) > 100:
        value *= Fraction(120, 100)
    if express:
        value *= Fraction(150, 100)
    return half_up(value)
# ----------------------------------------------------------------------------------


def main():
    try:
        args = json.load(sys.stdin)
        if not isinstance(args, dict):
            raise ValueError("input ต้องเป็น JSON object")
        result = shipping_fee(**args)
    except (ValueError, TypeError) as error:
        print(json.dumps({"ok": False, "error": str(error)}))
        return 2
    print(json.dumps({"ok": True, "result": result}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
