def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: ไม่คิดค่าปรับ
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วยเป็น 1/10000 ของสตางค์: 0.75% = 75, 15% = 1500
    scaled = min(amount * 75 * days_late, amount * 1500)
    return (scaled + 5000) // 10000
