def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า สูงสุด 15% ของยอดค้าง
    คำนวณด้วยจำนวนเต็มล้วนเพื่อเลี่ยงปัญหาทศนิยม ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3 or amount <= 0:
        return 0
    # หน่วยเป็น 1/10000 ของสตางค์: 0.75% = 75/10000, 15% = 1500/10000
    scaled = min(amount * 75 * days_late, amount * 1500)
    return (scaled + 5000) // 10000
