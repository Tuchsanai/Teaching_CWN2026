def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน ของทุกวันที่ช้า สูงสุด 15% ของยอดค้าง
    - ปัดเศษครึ่งขึ้น ใช้เลขจำนวนเต็มล้วน (ไม่มีปัญหา float)
    """
    if days_late <= 3:
        return 0
    # หน่วยเป็น 1/10000 ของสตางค์: 0.75% = 75, 15% = 1500
    num = amount * min(75 * days_late, 1500)
    return (num + 5000) // 10000
