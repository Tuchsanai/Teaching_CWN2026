def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: ไม่คิดค่าปรับ
    - ช้าเกิน 3 วัน: 0.75% ของยอดต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วนเพื่อเลี่ยงปัญหาทศนิยม ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # basis points: 0.75% = 75/10000, 15% = 1500/10000
    bp = min(days_late * 75, 1500)
    return (amount * bp * 2 + 10000) // 20000
