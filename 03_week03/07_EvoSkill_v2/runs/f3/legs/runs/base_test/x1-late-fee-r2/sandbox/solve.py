def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน ของยอดค้าง นับทุกวันที่ช้า
    - สูงสุด 15% ของยอดค้าง
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหาทศนิยม ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วย: 1/10000 ของ amount (0.75% = 75, 15% = 1500)
    rate = min(75 * days_late, 1500)
    return (amount * rate + 5000) // 10000
