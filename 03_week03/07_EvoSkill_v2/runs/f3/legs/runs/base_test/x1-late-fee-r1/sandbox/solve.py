def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน ของทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (ปัดเศษลง) เพื่อเลี่ยงข้อผิดพลาดทศนิยม
    """
    if days_late <= 3 or amount <= 0:
        return 0
    fee = amount * days_late * 75 // 10000
    cap = amount * 15 // 100
    return min(fee, cap)
