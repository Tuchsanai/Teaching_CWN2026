def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน ของยอดค้าง นับทุกวัน (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้าง
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3 or amount <= 0:
        return 0
    # หน่วย: amount * (basis points) / 10000 ; 0.75% = 75 bp, 15% = 1500 bp
    bp = min(75 * days_late, 1500)
    return (amount * bp + 5000) // 10000
