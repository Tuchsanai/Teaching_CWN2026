def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า
    - สูงสุด 15% ของยอด
    คำนวณด้วยจำนวนเต็มล้วน (ไม่มีปัญหา float) ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วยเป็น 1/10000 ของสตางค์: 0.75% = 75, 15% = 1500
    scaled = min(amount * 75 * days_late, amount * 1500)
    return (scaled + 5000) // 10000
