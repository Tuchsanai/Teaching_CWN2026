def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, คืนค่าเป็นจำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: ไม่คิดค่าปรับ
    - ช้าเกิน 3 วัน: 0.75% ของยอดต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - ค่าปรับสูงสุด 15% ของยอด
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา floating point; ปัดเศษแบบ half-up
    """
    if days_late <= 3:
        return 0
    # basis points: 0.75% = 75/10000, cap 15% = 1500/10000
    rate_bp_x100 = min(75 * days_late, 1500)  # หน่วย 1/10000 ของยอด
    return (amount * rate_bp_x100 * 2 + 10000) // 20000
