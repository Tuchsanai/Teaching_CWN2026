def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, คืนค่าเป็นจำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (ไม่มี float error) ปัดครึ่งขึ้น
    """
    if days_late <= 3 or amount <= 0:
        return 0
    # เศษส่วนของยอด หน่วย 1/10000: 0.75% = 75, 15% = 1500
    bp = min(75 * days_late, 1500)
    return (amount * bp * 2 + 10000) // 20000
