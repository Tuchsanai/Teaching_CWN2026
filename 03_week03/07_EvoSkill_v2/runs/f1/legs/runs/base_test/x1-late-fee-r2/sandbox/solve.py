def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอด
    คำนวณด้วยจำนวนเต็มล้วน (หน่วย 1/10000 ของยอด) ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    bp = min(75 * days_late, 1500)  # basis points ของยอดค้าง (0.75% = 75 bp)
    return (amount * bp + 5000) // 10000
