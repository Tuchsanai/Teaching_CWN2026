def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    basis_points = min(75 * days_late, 1500)  # 0.75% = 75 bp, เพดาน 15% = 1500 bp
    return (amount * basis_points * 2 + 10000) // 20000
