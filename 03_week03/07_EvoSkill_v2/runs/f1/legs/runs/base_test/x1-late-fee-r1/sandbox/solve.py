def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (หลีกเลี่ยงปัญหาทศนิยม) และปัดเศษลง
    """
    if days_late <= 3:
        return 0
    # 0.75% = 75/10000, 15% = 1500/10000
    return min(amount * 75 * days_late, amount * 1500) // 10000
