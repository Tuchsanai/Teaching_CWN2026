def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอด
    คำนวณด้วยจำนวนเต็มล้วน (ไม่มี float error) ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # ค่าปรับ = amount * 75 * days / 10000 ; เพดาน = amount * 1500 / 10000
    scaled = min(amount * 75 * days_late, amount * 1500)
    return (scaled + 5000) // 10000
