def shipping_fee(weight_g, distance_km, express):
    """ค่าส่ง (สตางค์, จำนวนเต็ม)"""
    need_int(weight_g, "weight_g", 1, 30000)
    if type(distance_km) not in (int, float):
        raise ValueError("distance_km ต้องเป็นตัวเลข")
    if distance_km != distance_km or distance_km in (float("inf"), float("-inf")) or distance_km < 0:
        raise ValueError("distance_km ต้องเป็นตัวเลข >= 0")
    need_bool(express, "express")
    # นโยบายร้าน S2: ส่งด่วนรับไม่เกิน 20000 กรัม
    if express and weight_g > 20000:
        raise ValueError("ส่งด่วนรับน้ำหนักไม่เกิน 20000 กรัม")
    # นโยบายร้าน S1: ระยะ 0 = รับเองที่ร้าน ค่าส่ง 0
    if distance_km == 0:
        return 0
    if weight_g <= 1000:
        fee = Fraction(4000)
    elif weight_g <= 5000:
        fee = Fraction(8000)
    else:
        fee = 8000 + Fraction((weight_g - 5000) * 1500, 1000)
    if Fraction(distance_km) > 100:
        fee *= Fraction(120, 100)
    if express:
        fee *= Fraction(150, 100)
    return half_up(fee)


