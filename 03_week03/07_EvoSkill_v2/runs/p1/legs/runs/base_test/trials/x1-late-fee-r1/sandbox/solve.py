def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (ไม่มีปัญหา float) ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วย 1/10000 ของ amount: 0.75% = 75, 15% = 1500
    rate = min(75 * days_late, 1500)
    return (amount * rate + 5000) // 10000
