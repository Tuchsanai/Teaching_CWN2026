def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวัน (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วย 1/10000 ของ amount: 0.75% = 75, 15% = 1500
    units = min(75 * days_late, 1500)
    num = amount * units
    return (2 * num + 10000) // 20000  # round half up of num/10000
