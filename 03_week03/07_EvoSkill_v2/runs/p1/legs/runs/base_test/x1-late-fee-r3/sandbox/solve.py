def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ต่อวัน นับทุกวัน (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    คำนวณด้วยจำนวนเต็มล้วน (หน่วย 1/10000 ของยอด) เพื่อเลี่ยงปัญหาทศนิยม
    ปัดเศษลง (ตัดเศษสตางค์)
    """
    if days_late <= 3:
        return 0
    basis_points = min(75 * days_late, 1500)  # 0.75% = 75/10000, cap 15% = 1500/10000
    return amount * basis_points // 10000
