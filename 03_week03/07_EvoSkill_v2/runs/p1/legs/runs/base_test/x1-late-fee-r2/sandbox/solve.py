def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า สูงสุด 15% ของยอด
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดเศษสตางค์แบบ half-up
    """
    if days_late <= 3:
        return 0
    # หน่วย: 1/10000 ของยอด (0.75% = 75, 15% = 1500)
    basis_points = min(75 * days_late, 1500)
    return (amount * basis_points + 5000) // 10000
