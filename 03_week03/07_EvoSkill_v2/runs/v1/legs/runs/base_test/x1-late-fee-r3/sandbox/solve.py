def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวัน (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้าง
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหา float; ปัดเศษครึ่งขึ้น
    """
    if days_late <= 3:
        return 0
    # หน่วย basis point ย่อย: 0.75% = 75/10000, 15% = 1500/10000
    rate = min(days_late * 75, 1500)
    return (amount * rate + 5000) // 10000
