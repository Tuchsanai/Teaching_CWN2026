def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, จำนวนเต็ม)

    - ช้า <= 3 วัน: 0
    - ช้า > 3 วัน: 0.75% ต่อวัน ของยอดค้าง นับทุกวันที่ช้า
    - สูงสุด 15% ของยอดค้าง
    ใช้เลขจำนวนเต็มล้วน (basis points) เพื่อเลี่ยงปัญหา float
    ปัดเศษครึ่งขึ้นเป็นสตางค์
    """
    if days_late <= 3:
        return 0
    bp = min(75 * days_late, 1500)  # basis points (1/10000)
    return (amount * bp + 5000) // 10000
