def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, ปัดครึ่งขึ้นเป็นจำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า
    - สูงสุด 15% ของยอด
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงความคลาดเคลื่อนของ float
    """
    if days_late <= 3:
        return 0
    # หน่วย: 1/10000 ของสตางค์  (0.75% = 75/10000, 15% = 1500/10000)
    raw = min(amount * 75 * days_late, amount * 1500)
    return (raw + 5000) // 10000
