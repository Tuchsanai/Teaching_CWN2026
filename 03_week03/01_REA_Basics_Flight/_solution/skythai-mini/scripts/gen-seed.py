#!/usr/bin/env python3
"""Generate db/init/02-seed.sql from data/flights-snapshot.json.
Usage: python3 scripts/gen-seed.py data/flights-snapshot.json db/init/02-seed.sql"""
import json, re, sys

src, dst = sys.argv[1], sys.argv[2]
snap = json.load(open(src, encoding="utf-8"))


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def minutes(text):
    h = re.search(r"(\d+)\s*ชม", text)
    m = re.search(r"(\d+)\s*นาที", text)
    return (int(h.group(1)) if h else 0) * 60 + (int(m.group(1)) if m else 0)


date = snap["query"]["date"]
cols = ("snapshot_rank, section, airline, operated_by, flight_date, dep_time, dep_airport_name, dep_iata, "
        "arr_time, arr_airport_name, arr_iata, arr_next_day, duration_text, duration_min, stops, layovers, "
        "price_thb, captured_at")
rows = []
for f in snap["flights"]:
    d, a = f["departure"], f["arrival"]
    rows.append("(" + ", ".join([
        q(f["rank"]), q(f["section"]), q(f["airline"]), q(f["operated_by"]), q(date),
        q(d["time"]), q(d["airport_name"]), q(d["iata"]),
        q(a["time"]), q(a["airport_name"]), q(a["iata"]), q(bool(a.get("next_day"))),
        q(f["duration"]), q(minutes(f["duration"])), q(f["stops"]),
        q(json.dumps(f["layovers"], ensure_ascii=False)) + "::jsonb",
        q(f["price"]["amount"]), q(snap["captured_at"]),
    ]) + ")")

with open(dst, "w", encoding="utf-8") as out:
    out.write(f"-- generated by scripts/gen-seed.py from {snap['schema']} ({len(rows)} flights)\n")
    out.write(f"INSERT INTO flights ({cols}) VALUES\n" + ",\n".join(rows) + ";\n")
print(f"wrote {len(rows)} flights to {dst}")
