def nfig(key, post="", title=None):
    f = FIG[key]
    return explain(title or f["title"], "img/%s.jpg" % key, f["steps"], post)


def has(src):
    return os.path.exists(os.path.join(E.ROOT, src))


def big(title, src, points, post=""):
    """ภาพใหญ่ราว 70% ของความกว้าง + ข้อความ 2-4 ข้อด้านขวา"""
    s = explain(title, src, points, post)
    s["body"] = s["body"].replace('<div class="ex">', '<div class="ex big">', 1)
    return s


def statement(title, photo, q, sub):
    """ข้อความใหญ่บนภาพถ่าย (คำถามหลักของบท)"""
    raw = ('<img class="bg" src="%s" alt="%s"><div class="shade"></div><div class="inner"><div class="q">%s</div>'
           '<div class="sub2">%s</div></div><div class="imgnote">ภาพจำลอง</div>') % (photo, E.esc(title), md(q), md(sub))
    return {"raw": raw, "cls": "stmt", "style": "", "title": title, "kicker": "", "tag": "", "lead": ""}


def ul_after(prefix, start="**อ่านผลอย่างไร**"):
    """รายการ (- ...) ที่ตามหลังย่อหน้าที่ขึ้นต้นด้วย start ในหัวข้อ prefix"""
    bl = sec(prefix)
    for k, b in enumerate(bl):
        if b["t"] == "p" and b["lines"][0].startswith(start):
            for x in bl[k + 1:]:
                if x["t"] == "ul":
                    return x["items"]
    raise KeyError("ไม่พบรายการหลัง %r ในหัวข้อ %r" % (start, prefix))


def ptext(prefix, start):
    return " ".join(para(prefix, start)["lines"])


def used_time(prefix):
    """เวลาจริงของขั้นจากบรรทัดตัวเอียงใต้ภาพคำตอบ (*ใช้เวลา ...*)"""
    t = ptext(prefix, "*ใช้เวลา").strip("*")
    return t.split(" · ")[0]


def shot(n, prefix, title, steps=None, note=""):
    """ส่วนหนึ่งของคำตอบจริง (ตัดจากภาพเต็ม) ภาพกว้างเต็มหน้า + ข้อ "อ่านผลอย่างไร" ของ README ด้านล่าง"""
    src, full = "img/c09-step%d.jpg" % n, "image/lab9-step%d.png" % n
    pts = steps or ul_after(prefix)[:4]
    side = "".join('<div class="stp"><span class="n">%d</span><span>%s</span></div>' % (k + 1, md(x)) for k, x in enumerate(pts))
    body = ('<div class="shotw"><div class="fig">%s</div><p class="cap">ส่วนหนึ่งของคำตอบจริง%s · ดู <a href="%s" target="_blank">ภาพคำตอบเต็ม</a></p>'
            '<div class="pts">%s</div></div>') % (E.img_tag({"src": src, "alt": E.plain(title)}), md(note), full, side)
    return S(title, body, maxfs=1.05)


