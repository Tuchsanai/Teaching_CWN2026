def progress(n):
    dots = "".join('<span class="%s"></span>' % ("cur" if k == n else "done" if k < n else "") for k in range(1, NSTEP + 1))
    return '<div class="prog">%s<em>ขั้นที่ %d จาก %d</em></div>' % (dots, n, NSTEP)


def head(n):
    """หน้าคั่น + ภาพของขั้น + พรอมต์ + รายการตรวจผล"""
    prefix, name, what, result = STEPS[n]
    CTX.update(kicker="ภาค LAB · ขั้นที่ %d จาก %d" % (n, NSTEP), group="ขั้นที่ %d · %s" % (n, name))
    add(E.divider("ขั้นที่ %d" % n, name, "<p>%s</p><p><b>ผลจริง</b> %s</p><p class=\"dim\">%s</p>%s" % (
        md(what), md(result), md(used_time(prefix)), progress(n))))
    pic = PICS.get(n)
    if pic:
        src, title, steps = pic
        if steps is None:
            add(nfig(os.path.splitext(os.path.basename(src))[0]))
        else:
            if not has(src):
                src = FALLBACK[n]
            add(big(title, src, steps, WEBNOTE if n == 10 else ""))
    add(E.prompt_slides(E.prompt_code(prefix), CTX["kicker"], "ขั้นที่ %d · %s" % (n, name)))
    items, ref = CHECKS[n]
    add(E.check_slide("step%d" % n, items, ref, NOTE_DIFF, "ขั้นที่ %d · %s" % (n, name)))


