def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (สตางค์, จำนวนเต็ม)

    - ช้าไม่เกิน 3 วัน: 0
    - ช้าเกิน 3 วัน: 0.75% ของยอด ต่อวัน นับทุกวันที่ช้า
    - สูงสุด 15% ของยอด
    คำนวณด้วยจำนวนเต็มล้วนเพื่อเลี่ยงความคลาดเคลื่อนของ float
    ปัดเศษครึ่งขึ้น (round half up)
    """
    if days_late <= 3:
        return 0
    # หน่วย: สตางค์ x 1/10000 (0.75% = 75/10000, 15% = 1500/10000)
    fee = min(amount * 75 * days_late, amount * 1500)
    return (fee + 5000) // 10000
