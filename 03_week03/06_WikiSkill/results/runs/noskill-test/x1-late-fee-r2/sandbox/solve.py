def late_fee(amount, days_late):
    """ค่าปรับชำระช้า (หน่วยสตางค์, คืนค่าเป็นจำนวนเต็ม)

    - ช้า <= 3 วัน: ไม่คิดค่าปรับ
    - ช้า > 3 วัน: 0.75% ต่อวัน นับทุกวันที่ช้า (รวม 3 วันแรก)
    - สูงสุด 15% ของยอดค้างชำระ
    ใช้เลขจำนวนเต็มล้วนเพื่อเลี่ยงปัญหาทศนิยม ปัดครึ่งขึ้น (half-up)
    """
    if days_late <= 3:
        return 0
    # fee = amount * 0.0075 * days = amount * 75 * days / 10000
    fee = (amount * 75 * days_late * 2 + 10000) // 20000
    # cap = amount * 15% (ปัดครึ่งขึ้นเช่นกัน)
    cap = (amount * 15 * 2 + 100) // 200
    return min(fee, cap)
