CREATE TABLE IF NOT EXISTS sites (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    full_name text NOT NULL,
    role text NOT NULL CHECK (role IN ('manager', 'supervisor', 'executive')),
    site_id integer REFERENCES sites (id),
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT users_role_site_check CHECK ((role = 'supervisor') = (site_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash text PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users (id),
    expires_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS upload_batches (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    site_id integer NOT NULL REFERENCES sites (id),
    uploaded_by integer NOT NULL REFERENCES users (id),
    -- Upper limit (BR-06) is enforced only by web/lib/rules.ts (POST /api/uploads).
    declared_count integer NOT NULL CHECK (declared_count >= 1),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS photos (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    batch_id uuid NOT NULL REFERENCES upload_batches (id),
    site_id integer NOT NULL REFERENCES sites (id),
    uploaded_by integer NOT NULL REFERENCES users (id),
    upload_date date NOT NULL DEFAULT ((now() AT TIME ZONE 'Asia/Bangkok')::date),
    original_filename text NOT NULL,
    mime text NOT NULL CHECK (mime IN ('image/jpeg', 'image/png')),
    -- Upper limit (BR-05) is enforced only by web/lib/rules.ts (bytes actually received).
    size_bytes bigint NOT NULL CHECK (size_bytes >= 1),
    sha256 text NOT NULL,
    storage_path text NOT NULL,
    status text NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED', 'PROCESSING', 'DONE', 'FAILED')),
    fail_reason text,
    dispatch_state text NOT NULL DEFAULT 'PENDING' CHECK (dispatch_state IN ('PENDING', 'SUBMITTED', 'CLOSED')),
    submit_attempts integer NOT NULL DEFAULT 0 CHECK (submit_attempts >= 0),
    accepted_at timestamptz NOT NULL DEFAULT now(),
    submitted_at timestamptz,
    finished_at timestamptz,
    model_h integer CHECK (model_h >= 0),
    model_v integer CHECK (model_v >= 0),
    model_result text CHECK (model_result IN ('PASS', 'WARN', 'FAIL')),
    current_result text CHECK (current_result IN ('PASS', 'WARN', 'FAIL')),
    is_overridden boolean NOT NULL DEFAULT false,
    model_version text,
    conf_threshold numeric,
    image_w integer,
    image_h integer
);

CREATE INDEX IF NOT EXISTS photos_site_date_result_idx ON photos (site_id, upload_date, current_result);
CREATE INDEX IF NOT EXISTS photos_batch_idx ON photos (batch_id);

CREATE OR REPLACE FUNCTION enforce_photo_model_result_write_once() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.model_h, NEW.model_v, NEW.model_result, NEW.model_version)
        IS DISTINCT FROM ROW(OLD.model_h, OLD.model_v, OLD.model_result, OLD.model_version)
        AND (OLD.status = 'DONE' OR NEW.status <> 'DONE') THEN
        RAISE EXCEPTION 'Model results can only be set when a photo becomes DONE' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER photos_model_result_write_once
    BEFORE UPDATE ON photos
    FOR EACH ROW EXECUTE FUNCTION enforce_photo_model_result_write_once();

CREATE TABLE IF NOT EXISTS detections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id uuid NOT NULL REFERENCES photos (id),
    cls text NOT NULL CHECK (cls IN ('NO_HARDHAT', 'NO_VEST')),
    confidence numeric NOT NULL,
    x1 integer NOT NULL,
    y1 integer NOT NULL,
    x2 integer NOT NULL,
    y2 integer NOT NULL
);

CREATE INDEX IF NOT EXISTS detections_photo_idx ON detections (photo_id);

CREATE TABLE IF NOT EXISTS result_overrides (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id uuid NOT NULL REFERENCES photos (id),
    edited_by integer NOT NULL REFERENCES users (id),
    edited_at timestamptz NOT NULL DEFAULT now(),
    result_before text NOT NULL CHECK (result_before IN ('PASS', 'WARN', 'FAIL')),
    result_after text NOT NULL CHECK (result_after IN ('PASS', 'WARN', 'FAIL')),
    reason text NOT NULL CHECK (reason ~ '[^[:space:]]')
);

CREATE INDEX IF NOT EXISTS result_overrides_photo_edited_at_idx ON result_overrides (photo_id, edited_at);

-- Run migrations as the table owner and grant sitesafe_web to a separate runtime login.
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'sitesafe_web') THEN
        CREATE ROLE sitesafe_web NOLOGIN;
    END IF;
END;
$$;

GRANT USAGE ON SCHEMA public TO sitesafe_web;
GRANT SELECT ON TABLE sites, users TO sitesafe_web;
GRANT SELECT, INSERT, DELETE ON TABLE sessions TO sitesafe_web;
GRANT SELECT, INSERT, UPDATE ON TABLE upload_batches, photos TO sitesafe_web;
GRANT SELECT, INSERT ON TABLE detections TO sitesafe_web;
REVOKE ALL PRIVILEGES ON TABLE result_overrides FROM PUBLIC, sitesafe_web;
GRANT SELECT, INSERT ON TABLE result_overrides TO sitesafe_web;
GRANT USAGE ON SEQUENCE detections_id_seq, result_overrides_id_seq TO sitesafe_web;
